  ('00000000-0000-4000-8000-000000000043'::uuid, 30),  -- Креативная стрижка
  ('00000000-0000-4000-8000-000000000045'::uuid, 15),  -- Окантовка
  ('00000000-0000-4000-8000-000000000046'::uuid, 15),  -- Стрижка под насадки
  ('00000000-0000-4000-8000-000000000048'::uuid, 100), -- Химзавивка на удлинённые волосы
  ('00000000-0000-4000-8000-000000000049'::uuid, 5),   -- Мытьё головы
  ('00000000-0000-4000-8000-000000000050'::uuid, 10),  -- Укладка
  ('00000000-0000-4000-8000-000000000051'::uuid, 5),   -- Женский зал: Чёлка
  ('00000000-0000-4000-8000-000000000052'::uuid, 15),  -- Детская стрижка
